# 预解析为 (network, country_code, display, code) 列表
_PARSED: list[tuple] = []
for net_str, cc, display, code in _BUILTIN_DB:
    try:
        _PARSED.append((ipaddress.ip_network(net_str), cc, display, code))
    except ValueError:
        pass


def lookup(ip_str: str) -> dict | None:
    """查询 IP 的地理位置。

    Returns:
        {"country_code": "RU", "display": "🇷🇺 俄罗斯", "code": "rus"} or None
    """
    try:
        ip = ipaddress.ip_address(ip_str)
    except ValueError:
        return None

    for net, cc, display, code in _PARSED:
        if ip in net:
            return {"country_code": cc, "display": display, "code": code}
    return None


def enrich_risk_detail(detail: str, ip_str: str) -> str:
    """在风险详情后追加 GeoIP 信息（如果命中）。"""
    geo = lookup(ip_str)
    if geo:
        return f"{detail} | 源: {geo['display']}"
    return detail
