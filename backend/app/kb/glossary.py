# 归一化索引：把变体拆开，统一映射到主条目
_INDEX: dict[str, str] = {}
for _term, _entry in GLOSSARY.items():
    for _variant in _term.split("|"):
        _INDEX[_variant.lower()] = _term


def lookup(term: str) -> dict | None:
    """查询单个术语，未命中返回 None。"""
    entry = _INDEX.get(term.lower().strip())
    return GLOSSARY[entry] if entry else None


def explain_terms(text: str, limit: int = 3) -> list[dict]:
    """在文本中找出已知术语，返回通俗解释列表（去重、限条数）。

    用于把检测报告/回答中的专业词自动"翻译"成大白话。
    """
    found: list[dict] = []
    seen: set[str] = set()
    for term in sorted(_INDEX, key=len, reverse=True):  # 长词优先匹配
        if term in text.lower():
            key = _INDEX[term]
            if key in seen:
                continue
            seen.add(key)
            found.append({"term": key.split("|")[0], **GLOSSARY[key]})
            if len(found) >= limit:
                break
    return found


def glossary_footer(text: str) -> str:
    """为文本追加"术语小课堂"脚注（无术语时返回空串）。"""
    items = explain_terms(text)
    if not items:
        return ""
    lines = ["\n\n📖 术语小课堂："]
    for item in items:
        lines.append(f"· **{item['term']}**：{item['plain']}")
        if item.get("advice"):
            lines.append(f"   🛡️ {item['advice']}")
    return "\n".join(lines)
